import { type Env, parseEnv } from "@agenthabit/config";
import { AgentHabitError } from "@agenthabit/core";

import { fillEnvValues, parseEnv as parseEnvFile, readEnvFile, writeEnvFile } from "./env-file.js";
import {
  evmAddress,
  type KeyGenerator,
  missingKeys,
  ROLES,
  randomKeys,
  stellarAddress,
} from "./keys.js";
import { MANUAL_FAUCETS } from "./network.js";
import type { StellarTestnet } from "./stellar-testnet.js";

export interface BootstrapOptions {
  /** `.env.local`: where the keys live. Created from `examplePath` on the first run. */
  readonly envPath: string;
  readonly examplePath: string;
  readonly connectStellar: (rpcUrl: string) => StellarTestnet;
  /** Receives every output line, already checked for secrets. */
  readonly print: (line: string) => void;
  readonly keys?: KeyGenerator;
}

export interface BootstrapReport {
  /** Variables generated by this run. Every other key was kept as it was. */
  readonly created: readonly string[];
  /** Stellar addresses funded with Friendbot by this run. */
  readonly funded: readonly string[];
  readonly trustline: "created" | "already in place";
}

/**
 * Wraps `print` so a line carrying any secret (or an EVM key without its `0x`) is never written:
 * it stops the run with `SecretLeak` instead. The test suite proves no line trips it; this is
 * the guard for the line nobody thought to test.
 */
export function guardSecrets(
  secrets: readonly string[],
  print: (line: string) => void,
): (line: string) => void {
  const forbidden = secrets.flatMap((secret) =>
    secret.startsWith("0x") ? [secret, secret.slice(2)] : [secret],
  );
  const lowered = forbidden.map((value) => value.toLowerCase());
  return (line) => {
    const haystack = line.toLowerCase();
    if (lowered.some((value) => haystack.includes(value))) {
      throw new AgentHabitError("SecretLeak", "refused to print a line that contains a secret");
    }
    print(line);
  };
}

function secretsOf(env: Env): string[] {
  return ROLES.flatMap((role) => [env[role.stellar], env[role.avalanche]]).filter(
    (value) => value !== undefined,
  );
}

/** Reads and validates `.env.local`, seeding it from `.env.example` when it does not exist. */
async function loadEnvFile(options: BootstrapOptions): Promise<{ contents: string; env: Env }> {
  const contents = (await readEnvFile(options.envPath)) ?? (await readEnvFile(options.examplePath));
  if (contents === undefined) {
    throw new AgentHabitError("ConfigError", "neither .env.local nor .env.example exists", {
      details: { envPath: options.envPath, examplePath: options.examplePath },
    });
  }
  return { contents, env: parseEnv(Object.fromEntries(parseEnvFile(contents))) };
}

function required<T>(value: T | undefined, variable: string): T {
  if (value === undefined) {
    throw new AgentHabitError("ConfigError", `${variable} is still missing after key generation`, {
      details: { variable },
    });
  }
  return value;
}

/**
 * Generates the testnet keys that are missing, funds the Stellar accounts that do not exist yet,
 * adds the test user's USDC trustline if it is not there, and prints what to do by hand on Fuji.
 * Safe to run any number of times: an existing key, account or trustline is never touched.
 */
export async function runBootstrap(options: BootstrapOptions): Promise<BootstrapReport> {
  const loaded = await loadEnvFile(options);
  const fresh = missingKeys(loaded.env, options.keys ?? randomKeys);
  const created = [...fresh.keys()];

  let env = loaded.env;
  if (fresh.size > 0) {
    const contents = fillEnvValues(loaded.contents, fresh);
    env = parseEnv(Object.fromEntries(parseEnvFile(contents)));
    await writeEnvFile(options.envPath, contents);
  }

  const print = guardSecrets(secretsOf(env), options.print);
  const identities = ROLES.map((role) => {
    const stellarSecret = required(env[role.stellar], role.stellar);
    const avalancheKey = required(env[role.avalanche], role.avalanche);
    return {
      role,
      stellarSecret,
      stellar: stellarAddress(stellarSecret),
      avalanche: evmAddress(avalancheKey),
      isNew: created.includes(role.stellar) || created.includes(role.avalanche),
    };
  });

  print("AgentHabit bootstrap: Stellar testnet and Avalanche Fuji");
  print(`Keys in ${options.envPath} (secrets are never printed):`);
  for (const identity of identities) {
    const state = identity.isNew ? "created" : "kept";
    print(`  ${identity.role.name.padEnd(9)} ${state.padEnd(7)} stellar ${identity.stellar}`);
    print(`  ${"".padEnd(17)} avalanche ${identity.avalanche}`);
  }

  const stellar = options.connectStellar(env.STELLAR_RPC_URL);
  await stellar.assertTestnet();

  print("Stellar testnet:");
  const funded: string[] = [];
  for (const identity of identities) {
    if (await stellar.accountExists(identity.stellar)) {
      print(`  ${identity.role.name.padEnd(9)} account already funded`);
      continue;
    }
    await stellar.fund(identity.stellar);
    funded.push(identity.stellar);
    print(`  ${identity.role.name.padEnd(9)} account funded with Friendbot`);
  }

  const testUser = required(identities.at(-1), "STELLAR_TEST_USER_SECRET");
  let trustline: BootstrapReport["trustline"] = "already in place";
  if (await stellar.hasUsdcTrustline(testUser.stellar)) {
    print("  test user USDC trustline already in place");
  } else {
    const hash = await stellar.addUsdcTrustline(testUser.stellarSecret);
    trustline = "created";
    print(`  test user USDC trustline created (transaction ${hash})`);
  }

  print("By hand (bootstrap never touches these faucets):");
  print(`  1. Test AVAX for gas on Fuji, for each address: ${MANUAL_FAUCETS.fujiAvax}`);
  for (const identity of identities) {
    print(`       ${identity.role.name.padEnd(9)} ${identity.avalanche}`);
  }
  print(`  2. Test USDC for the test user: ${MANUAL_FAUCETS.circleUsdc}`);
  print(`       Stellar testnet ${testUser.stellar}`);
  print(`       Avalanche Fuji  ${testUser.avalanche}`);

  return { created, funded, trustline };
}
